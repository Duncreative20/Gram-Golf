// DTCG (tokens/figma/*.dtcg.json) → src/generated/*.ts. Chạy: pnpm -F @gr/ds build:tokens
import StyleDictionary from 'style-dictionary';
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const FIG = resolve(here, 'figma');
const OUT = resolve(here, '../src/generated');
mkdirSync(OUT, { recursive: true });
const present = new Set(readdirSync(FIG));

StyleDictionary.registerFormat({
  name: 'gr/ts-flat',
  format: ({ dictionary, options }) => {
    const rows = dictionary.allTokens
      .filter((t) => t.path[0] === options.group)
      .map((t) => `  ${JSON.stringify(t.path.slice(1).join('/'))}: ${JSON.stringify(t.$value)},`)
      .sort();
    return `// generated by tokens/build.mjs — do not edit\nexport const ${options.exportName} = {\n${rows.join('\n')}\n} as const;\n`;
  },
});

// Mỗi set = nguồn đủ để resolve alias + các file sinh ra từ set đó: [destination, exportName, group]
const BASE = [
  'global-dimensions.mode-1.dtcg.json', 'spacing.standard.dtcg.json', 'radius.rounded.dtcg.json',
  'component-size.default.dtcg.json', 'emphasis.medium.dtcg.json', 'breakpoints.mobile.dtcg.json',
  'typography.global-base-14.dtcg.json',
];
const COLORS = (scheme) => ['global-colors.gr.dtcg.json', 'base-colors.gr.dtcg.json', `semantic.${scheme}.dtcg.json`];
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const SETS = [
  { source: BASE, files: [
    ['primitives.ts', 'globalDimensions', 'global-dimensions'],
    ['spacing.ts', 'spacing', 'spacing'], ['radius.ts', 'radius', 'radius'], ['size.ts', 'size', 'component-size'],
    ['weight.ts', 'emphasis', 'emphasis'], ['breakpoints.ts', 'breakpoints', 'breakpoints'], ['typography.ts', 'typography', 'typography'],
  ] },
  { source: COLORS('light'), files: [['theme.light.ts', 'themeLight', 'semantic'], ['primitives.colors.ts', 'globalColors', 'global-colors']] },
  { source: COLORS('dark'), files: [['theme.dark.ts', 'themeDark', 'semantic']] },
  ...['light', 'dark'].flatMap((scheme) => ['neutral', 'brand'].map((em) => ({
    source: [...COLORS(scheme), `component.${em}-emphasis-s1.dtcg.json`, ...BASE],
    files: [[`component.${em}.${scheme}.ts`, `component${cap(em)}${cap(scheme)}`, 'component']],
  }))),
  { source: ['text-styles.dtcg.json', 'effects.dtcg.json'], files: [['textStyles.ts', 'textStyles', 'text-styles'], ['effects.ts', 'effects', 'effects']] },
];

const exportNames = {};
for (const set of SETS) {
  const source = set.source.filter((f) => present.has(f)).map((f) => resolve(FIG, f));
  const files = set.files.filter(([, , group]) => set.source.some((f) => f.startsWith(group + '.') && present.has(f)));
  if (files.length === 0) continue;
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    source,
    platforms: {
      ts: {
        buildPath: OUT + '/',
        files: files.map(([destination, exportName, group]) => ({ destination, format: 'gr/ts-flat', options: { exportName, group } })),
      },
    },
  });
  await sd.buildAllPlatforms();
  for (const [d, e] of files) exportNames[d] = e;
}

// keys.ts: union type cho từng map đã sinh (tên type theo tên file: theme.light.ts → ThemeLightKey)
const gen = readdirSync(OUT).filter((f) => f.endsWith('.ts') && f !== 'keys.ts').sort();
const lines = [];
for (const f of gen) {
  const name = f.replace(/\.ts$/, '');
  const exportName = exportNames[f];
  if (!exportName) continue;
  const typeName = cap(name.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase())) + 'Key';
  lines.push(`import { ${exportName} } from './${name}';`, `export type ${typeName} = keyof typeof ${exportName};`);
}
writeFileSync(resolve(OUT, 'keys.ts'), `// generated by tokens/build.mjs — do not edit\n${lines.join('\n')}\n`);
console.log('generated:', gen.join(', '));
